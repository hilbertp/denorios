// ── the fixture claude ──────────────────────────────────────────────────────
// A step machine: the knobs file says what to write, when to pause, what to
// commit and what to exit with. It hashes everything it puts on stdout, so a
// 300 MB session can be compared with its log without either being read twice.

const FAKE_CLAUDE = `'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const knobs = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const hash = crypto.createHash('sha256');
let bytesOut = 0;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function push(stream, buf) {
  // Resolved by the write callback, not by the return value: a true return only
  // means "buffered", and exiting on a buffered pipe loses the tail.
  return new Promise((resolve) => stream.write(buf, () => resolve()));
}
function out(buf) {
  hash.update(buf);
  bytesOut += buf.length;
  return push(process.stdout, buf);
}
function err(buf) { return push(process.stderr, buf); }

function readStdin() {
  return new Promise((resolve) => {
    const parts = [];
    process.stdin.on('data', (c) => parts.push(c));
    process.stdin.on('end', () => resolve(Buffer.concat(parts)));
    process.stdin.on('error', () => resolve(Buffer.concat(parts)));
  });
}

function gitIn(cwd, args) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
}

async function run() {
  for (const step of knobs.steps) {
    switch (step.op) {
      case 'stdin': {
        const buf = await readStdin();
        fs.writeFileSync(step.file, buf);
        break;
      }
      case 'pid':
        fs.writeFileSync(step.file, String(process.pid));
        break;
      case 'line':
        await out(Buffer.from(JSON.stringify(step.obj) + '\\n'));
        break;
      case 'raw':
        await out(Buffer.from(step.text, 'utf8'));
        break;
      case 'rawBytes':
        await out(Buffer.from(step.bytes));
        break;
      case 'bulk': {
        // stream-json the size of a real long build, made of ordinary assistant
        // turns so the attribution has something to walk.
        const pad = 'x'.repeat(step.lineBytes || 32768);
        let written = 0;
        while (written < step.bytes) {
          const line = Buffer.from(JSON.stringify({
            type: 'assistant',
            session_id: step.sessionId || 'bulk',
            message: { content: [{ type: 'text', text: pad }] },
          }) + '\\n');
          await out(line);
          written += line.length;
        }
        break;
      }
      case 'stderr':
        await err(Buffer.from(step.text, 'utf8'));
        break;
      case 'sleep':
        await sleep(step.ms);
        break;
      case 'repeat': {
        for (let i = 0; i < step.count; i++) {
          await sleep(step.ms);
          const text = String(step.text).replace('{i}', String(i));
          if (step.stream === 'stderr') await err(Buffer.from(text, 'utf8'));
          else await out(Buffer.from(text, 'utf8'));
        }
        break;
      }
      case 'forever': {
        // Talks until something kills it — the pause/resume/abort probe.
        for (let i = 0; ; i++) {
          await sleep(step.ms);
          await out(Buffer.from('{"type":"assistant","tick":' + i + '}\\n'));
        }
      }
      case 'done': {
        const dir = path.join(process.cwd(), 'bridge', 'queue');
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(path.join(dir, step.id + '-DONE.md'), step.content);
        break;
      }
      case 'commit': {
        const cwd = process.cwd();
        fs.writeFileSync(path.join(cwd, step.file), step.content);
        gitIn(cwd, ['add', step.file]);
        gitIn(cwd, ['commit', '--quiet', '-m', step.message]);
        break;
      }
      case 'verdict': {
        const dir = path.join(process.cwd(), 'bridge', 'queue');
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(path.join(dir, step.id + '-NOG.md'), step.content);
        break;
      }
      case 'dirty':
        fs.writeFileSync(path.join(process.cwd(), step.file), step.content);
        break;
      case 'pattern': {
        // Exactly step.count copies of a fixed unit, so the test knows the
        // session's bytes without reading them back.
        const unit = Buffer.from(step.unit, 'utf8');
        const per = step.chunkUnits || 64;
        let left = step.count;
        while (left > 0) {
          const n = Math.min(per, left);
          const parts = [];
          for (let i = 0; i < n; i++) parts.push(unit);
          const buf = Buffer.concat(parts);
          if (step.stream === 'stderr') await err(buf); else await out(buf);
          left -= n;
        }
        break;
      }
      case 'stamp':
        fs.writeFileSync(step.file, String(Date.now()));
        break;
      case 'hash':
        fs.writeFileSync(step.file, JSON.stringify({ sha256: hash.copy().digest('hex'), bytes: bytesOut }));
        break;
      default:
        throw new Error('unknown step ' + step.op);
    }
  }
}

run().then(() => {
  // exitCode, never process.exit: the pipes drain on the way out, so the last
  // bytes of a 300 MB session are in the log the test compares against.
  process.exitCode = knobs.exitCode || 0;
}, (e) => {
  process.stderr.write('fixture claude failed: ' + e.stack + '\\n');
  process.exitCode = 90;
});
`;

