test('J-session-streamed — trap 4: the tracked child is the real process, so pause, resume and abort still reach it', async () => {
  // The dashboard's three controls signal activeChildren through .pid and read
  // .exitCode. What invokeRom puts there is what streamSession returns.
  assert.match(ORCH_SRC, /const child = streamSession\(/,
    'invokeRom must keep the child the session helper returns');
  assert.match(ORCH_SRC, /activeChildren\.set\(String\(id\), \{ child, worktreePath \}\);/,
    'and that child is what pause/resume/abort are given');

  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'j-session-streamed-signals-'));
  tmpDirs.push(tmp);
  const script = path.join(tmp, 'talker.js');
  fs.writeFileSync(script, `
    let n = 0;
    setInterval(() => { process.stdout.write('{"type":"assistant","tick":' + (n++) + '}\\n'); }, 50);
  `);
  const logPath = path.join(tmp, 'session.log');

  const closed = new Promise((resolve) => {
    const child = streamSession(
      { command: process.execPath, args: [script], cwd: tmp, prompt: 'go', logPath },
      (outcome) => resolve({ outcome, child }),
    );

    assert.equal(typeof child.pid, 'number', 'the helper returns a real child process');
    assert.equal(child.exitCode, null, 'which reads as alive while it runs');

    const size = () => { try { return fs.statSync(logPath).size; } catch (_) { return 0; } };
    const wait = (ms) => new Promise((r) => setTimeout(r, ms));

    (async () => {
      await wait(400);
      assert.ok(size() > 0, 'the session is talking');

      process.kill(child.pid, 'SIGSTOP');
      await wait(300);
      const paused = size();
      await wait(400);
      assert.equal(size(), paused, 'pausing the tracked child stops its output');

      process.kill(child.pid, 'SIGCONT');
      await wait(400);
      assert.ok(size() > paused, 'resuming it starts the output again');

      process.kill(child.pid, 'SIGKILL');
    })();
  });

  const { outcome, child } = await closed;
  assert.equal(outcome.signal, 'SIGKILL', 'abort ends the process');
  assert.notEqual(child.exitCode === null && child.signalCode === null, true,
    'and the entry reads as finished afterwards');
});

