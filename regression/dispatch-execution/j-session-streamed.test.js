/** Runs one Sam session end to end and returns everything it left behind. */
function runRom(fx, { steps, exitCode = 0, inactivityMs = 300000, slice, command, args, timeoutMs = 240000 }) {
  const id = fx.id;
  const inProgressPath = path.join(fx.queue, `${id}-IN_PROGRESS.md`);
  fs.writeFileSync(inProgressPath, slice || sliceFile(id));
  fs.writeFileSync(fx.knobs, JSON.stringify({ steps, exitCode }));
  writeConfig(fx, { command, args });
  fs.writeFileSync(fx.job, JSON.stringify({
    role: 'rom',
    work: fx.work,
    id,
    inProgressPath,
    donePath: path.join(fx.queue, `${id}-DONE.md`),
    errorPath: path.join(fx.queue, `${id}-ERROR.md`),
    inactivityMs,
    title: `Streamed session ${id}`,
    goal: 'stream it',
    memFile: fx.mem,
  }));

  const proc = spawnSync(process.execPath, [fx.driver, fx.job], {
    cwd: fx.work, encoding: 'utf8', timeout: timeoutMs,
    env: { ...process.env, ...GIT_ENV, NO_COLOR: '1' },
    maxBuffer: 64 * 1024 * 1024,
  });
  return { proc, ...readBack(fx, id) };
}

function readBack(fx, id) {
  const read = (p) => { try { return fs.readFileSync(p, 'utf8'); } catch (_) { return null; } };
  const events = (read(fx.register) || '').split('\n').filter(Boolean)
    .map((l) => { try { return JSON.parse(l); } catch (_) { return null; } })
    .filter((e) => e && String(e.slice_id || e.id || '') === String(id));
  return {
    events,
    eventsOf: (name) => events.filter((e) => e.event === name),
    logPath: path.join(fx.logs, `rom-${id}.log`),
    log: () => read(path.join(fx.logs, `rom-${id}.log`)),
    timing: () => { const t = read(path.join(fx.logs, `rom-${id}.timing.json`)); return t ? JSON.parse(t) : null; },
    errorFile: read(path.join(fx.queue, `${id}-ERROR.md`)),
    errorJson: (() => { const t = read(path.join(fx.errors, `${id}-ERROR.json`)); return t ? JSON.parse(t) : null; })(),
    doneFile: read(path.join(fx.queue, `${id}-DONE.md`)),
    parked: read(path.join(fx.queue, `${id}-PARKED.md`)),
    queued: read(path.join(fx.queue, `${id}-QUEUED.md`)),
    memory: (() => { const t = read(fx.mem); return t ? JSON.parse(t) : null; })(),
  };
}

